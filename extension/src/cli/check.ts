// `flaglens check`: the editor's checks for a whole repository, for CI. Pure: the caller fetches the project's flags and
// environment documents from Flagsmith and lists the files; this finds the problems and renders a Markdown report
// (a GitHub job summary or pull-request comment).
import { suggestKey } from '../core/analysis';
import type { EnvironmentDocument } from '../core/engine';
import { analyseRules, type RuleFinding } from '../core/rules';
import { compilePatterns, DEFAULT_EXTRA_PATTERNS, findFlagReferences } from '../core/scanner';

export interface CheckInput {
  project: string;
  flags: { name: string; archived: boolean }[];
  documents: EnvironmentDocument[];
  files: { path: string; text: string }[];
  extraPatterns?: readonly string[];
}

export interface Located {
  path: string;
  line: number;
  key: string;
}

export interface CheckResult {
  project: string;
  references: number;
  unknown: (Located & { suggestion?: string })[];
  archived: Located[];
  rules: RuleFinding[];
  unused: string[];
  /** Problems that should fail a strict check: unknown keys, archived flags in code, rule findings. */
  problems: number;
}

export function runCheck(input: CheckInput): CheckResult {
  const patterns = compilePatterns(input.extraPatterns ?? DEFAULT_EXTRA_PATTERNS);
  const known = new Map(input.flags.map((f) => [f.name, f]));
  const unknown: CheckResult['unknown'] = [];
  const archived: Located[] = [];
  const used = new Set<string>();
  let references = 0;
  for (const file of input.files) {
    for (const r of findFlagReferences(file.text, patterns)) {
      references++;
      const flag = known.get(r.key);
      const at = { path: file.path, line: r.line + 1, key: r.key };
      if (!flag) unknown.push({ ...at, suggestion: suggestKey(r.key, known.keys()) });
      else {
        used.add(r.key);
        if (flag.archived) archived.push(at);
      }
    }
  }
  const rules = input.documents.flatMap((d) => analyseRules(d));
  const unused = input.flags.filter((f) => !f.archived && !used.has(f.name)).map((f) => f.name).sort();
  return { project: input.project, references, unknown, archived, rules, unused, problems: unknown.length + archived.length + rules.length };
}

const KIND: Record<string, string> = {
  shadowed: 'Never applies (shadowed)',
  redundant: 'Changes nothing (redundant)',
  'matches-nobody': 'Matches nobody',
  'default-unreachable': 'Default nobody gets',
};
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Markdown for a job summary or a pull-request comment. `link` turns a path and line into a URL. */
export function checkMarkdown(r: CheckResult, link?: (path: string, line: number) => string): string {
  const where = (l: Located) => (link ? `[${l.path}:${l.line}](${link(l.path, l.line)})` : `${l.path}:${l.line}`);
  const out: string[] = [`## FlagLens check: ${r.project}`, ''];
  out.push(
    r.problems
      ? `**${r.problems} problem${r.problems === 1 ? '' : 's'}** in ${r.references} flag references and the project's targeting rules.`
      : `**No problems** in ${r.references} flag references and the project's targeting rules.`,
    '',
  );
  if (r.unknown.length) {
    out.push('### Unknown flag keys', '', 'Every Flagsmith SDK returns the default for a key it does not know, so this code may never run.', '');
    out.push('| Where | Key | Did you mean |', '|---|---|---|');
    for (const u of r.unknown) out.push(`| ${where(u)} | \`${cell(u.key)}\` | ${u.suggestion ? `\`${u.suggestion}\`` : ''} |`);
    out.push('');
  }
  if (r.archived.length) {
    out.push('### Archived flags still in code', '', '| Where | Flag |', '|---|---|');
    for (const a of r.archived) out.push(`| ${where(a)} | \`${cell(a.key)}\` |`);
    out.push('');
  }
  if (r.rules.length) {
    out.push('### Targeting rules', '', 'Each finding holds for every possible user.', '', '| Flag | Environment | Problem | Details |', '|---|---|---|---|');
    for (const f of r.rules) out.push(`| \`${cell(f.flag)}\` | ${cell(f.environment)} | ${KIND[f.kind] ?? f.kind} | ${cell(f.message)} |`);
    out.push('');
  }
  if (r.unused.length) {
    out.push(`<details><summary>${r.unused.length} flag${r.unused.length === 1 ? '' : 's'} no file references</summary>`, '', r.unused.map((u) => `\`${u}\``).join(', '), '', '</details>', '');
  }
  out.push('<sub>Generated by [FlagLens](https://github.com/Pranav-Singh-Devloper/flaglens) against self-hosted Flagsmith.</sub>', '');
  return out.join('\n');
}
